import {readFile,writeFile,stat} from 'node:fs/promises';
import {createReadStream} from 'node:fs';
import path from 'node:path';
import {createHash,sign,verify} from 'node:crypto';
import {UPDATE_PUBLIC_KEY,canonicalRelease} from '../shared/update-protocol.js';
const zip=path.resolve(process.argv[2]||'');
if(!zip.endsWith('.zip')||!process.env.MAGIC_UPDATE_SIGNING_KEY)throw Error('指定桌面ZIP和MAGIC_UPDATE_SIGNING_KEY私钥路径');
const folder=path.basename(zip,'.zip'),version=JSON.parse(await readFile(path.join(path.dirname(zip),folder,'VERSION.json'),'utf8'));
const hash=createHash('sha256');for await(const chunk of createReadStream(zip))hash.update(chunk);
const release={version:version.clientVersion,gameVersion:version.gameVersion,protocolVersion:version.protocolVersion,platform:'win32',arch:version.arch,sha256:hash.digest('hex'),size:(await stat(zip)).size,file:'package.zip',folder};
const signature=sign(null,Buffer.from(canonicalRelease(release)),await readFile(process.env.MAGIC_UPDATE_SIGNING_KEY)).toString('base64');
if(!verify(null,Buffer.from(canonicalRelease(release)),UPDATE_PUBLIC_KEY,Buffer.from(signature,'base64')))throw Error('发布私钥与客户端信任的公钥不匹配');
const manifest=zip+'.manifest.json';await writeFile(manifest,JSON.stringify({release,signature},null,2)+'\n');
console.log(JSON.stringify({manifest,version:release.version,size:release.size,sha256:release.sha256}));
